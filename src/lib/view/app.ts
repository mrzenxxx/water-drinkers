/**
 * Название приложения и заголовки вкладок.
 *
 * Название лежит в одном месте, а не в четырнадцати заголовках подряд:
 * переименование иначе означает четырнадцать правок, из которых одну
 * обязательно забудут — и вкладка останется со старым именем.
 */

export const APP_NAME = 'ГИС Пузырик';

/** Заголовок вкладки: «Раздел — Название». */
export function pageTitle(section: string): string {
  return `${section} — ${APP_NAME}`;
}
