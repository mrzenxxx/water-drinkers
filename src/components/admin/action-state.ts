/**
 * Состояние формы админ-панели.
 *
 * Живёт отдельным модулем, потому что нужен по обе стороны границы: серверные
 * действия (`src/lib/actions/admin.ts`) возвращают этот тип, клиентские формы
 * его читают через `useActionState`. Положить его в файл с директивой
 * `'use server'` нельзя — оттуда разрешено экспортировать только асинхронные
 * функции, и константа `IDLE` уронила бы сборку.
 */

export type ActionState = {
  status: 'idle' | 'success' | 'error';
  message: string;
};

export const IDLE: ActionState = { status: 'idle', message: '' };

