import type { ReactNode } from 'react';

/**
 * Знаки мессенджеров: Telegram и MAX.
 *
 * Отдельный файл, потому что это не наши значки. Остальной интерфейс рисует
 * `lucide` — однотонный контур в цвете текста, — а здесь чужие торговые знаки,
 * и узнают их именно по цвету: синий кружок с самолётиком и сине-фиолетовая
 * плитка с облачком. Значок в цвете текста рядом с ними читался бы как «ещё
 * одна кнопка приложения», а не как «вот этот мессенджер». Поэтому цвета
 * заданы прямо в разметке и темой не управляются: марка одна и та же на
 * светлом и на тёмном.
 *
 * Оба знака нарисованы в квадрате 24×24 и заливают его целиком — это плитки
 * приложений, а не контурные значки, и поля им даёт кнопка, а не сам рисунок.
 *
 * Цвет MAX — из фирменной палитры (`#471AFF` → `#9500FF`). Идентификатор
 * градиента постоянный: на одной странице знак стоит один раз, а одинаковые
 * определения с одним именем браузер разрешает в первое — то же самое.
 *
 * `aria-hidden`: знак всегда стоит внутри ссылки, у которой есть подпись, и
 * называть мессенджер дважды незачем.
 */

type MarkProps = {
  className?: string;
};

const MAX_GRADIENT_ID = 'max-mark-gradient';

export function TelegramMark({ className }: MarkProps): ReactNode {
  return (
    <svg viewBox="0 0 24 24" aria-hidden focusable="false" className={className}>
      <circle cx="12" cy="12" r="12" fill="#229ED9" />
      <path
        fill="#fff"
        d="M16.906 7.224c.1-.002.321.023.465.14a.5.5 0 0 1 .171.325c.016.093.036.306.02.472c-.18 1.898-.962 6.502-1.36 8.627c-.168.9-.499 1.201-.82 1.23c-.696.065-1.225-.46-1.9-.902c-1.056-.693-1.653-1.124-2.678-1.8c-1.185-.78-.417-1.21.258-1.91c.177-.184 3.247-2.977 3.307-3.23c.007-.032.014-.15-.056-.212s-.174-.041-.249-.024q-.159.037-5.061 3.345q-.72.495-1.302.48c-.428-.008-1.252-.241-1.865-.44c-.752-.245-1.349-.374-1.297-.789q.04-.324.893-.663q5.247-2.286 6.998-3.014c3.332-1.386 4.025-1.627 4.476-1.635"
      />
    </svg>
  );
}

export function MaxMark({ className }: MarkProps): ReactNode {
  return (
    <svg viewBox="0 0 24 24" aria-hidden focusable="false" className={className}>
      <defs>
        <linearGradient
          id={MAX_GRADIENT_ID}
          x1="0"
          y1="0"
          x2="24"
          y2="24"
          gradientUnits="userSpaceOnUse"
        >
          <stop stopColor="#471AFF" />
          <stop offset="1" stopColor="#9500FF" />
        </linearGradient>
      </defs>
      <rect width="24" height="24" rx="6.5" fill={`url(#${MAX_GRADIENT_ID})`} />
      {/*
        Облачко нарисовано в своей сетке 48×48 и уменьшено до плитки; толщина
        обводки поднята во столько же раз, во сколько уменьшен рисунок, иначе
        линия истончилась бы вместе с ним.
      */}
      <g transform="translate(2.16 2.11) scale(.41)">
        <path
          fill="none"
          stroke="#fff"
          strokeWidth="5"
          strokeLinecap="round"
          strokeLinejoin="round"
          d="M15.63 40.465c8.083 7.193 27.86-1.166 27.783-15.85C43.36 14.546 35.107 4.59 24.873 4.5c-9.538-.083-19.648 5.962-20.23 17.767c-.172 3.515 0 8.859 1.231 11.73c2.335 6.7.113 8.477 2.804 9.328q3.617.9 6.953-2.861"
        />
      </g>
    </svg>
  );
}
