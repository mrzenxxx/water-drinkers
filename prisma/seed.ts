import 'dotenv/config';

import { prisma } from '../src/lib/db';

/**
 * Наполнение базы: строка настроек фонда, первый администратор и закреплённая
 * инструкция в разделе «Объявления» (§6.12).
 *
 * Остальные участники заводятся администратором через `addParticipant`
 * (этап 4), а не здесь: состав команды меняется и в коде ему не место.
 *
 * Имя и фамилия намеренно не заполняются — человек вводит их сам при
 * первом входе (§7), приложение не выдумывает персональные данные.
 */
const ADMIN_EMAIL = 'e.kondobarov@sspk.spb.ru';

async function main(): Promise<void> {
  await prisma.fundSettings.upsert({
    where: { id: 1 },
    update: {},
    create: { id: 1 },
  });

  const admin = await prisma.user.upsert({
    where: { email: ADMIN_EMAIL },
    update: { role: 'ADMIN' },
    create: {
      email: ADMIN_EMAIL,
      role: 'ADMIN',
      joinedAt: new Date(),
    },
  });

  /**
   * Закреплённая инструкция: раздел объявлений не должен встречать человека
   * пустым экраном, а правила кассы всё равно надо где-то написать.
   *
   * Заводится один раз и потом правится администратором через интерфейс,
   * поэтому повторный запуск сида её не переписывает: иначе он затирал бы
   * живой текст, который кто-то уже поправил.
   */
  const guideTitle = 'Как пользоваться кассой';
  const guide = await prisma.announcement.findFirst({ where: { title: guideTitle } });

  if (guide === null) {
    await prisma.announcement.create({
      data: {
        title: guideTitle,
        pinned: true,
        publishedAt: new Date(),
        createdBy: admin.id,
        body: [
          'Касса собирает деньги на бутилированную воду. Всё, что в неё внесено и из неё',
          'потрачено, видно всем: приложение прозрачно, участник видит то же, что администратор.',
          '',
          'Как внести взнос:',
          '1. Откройте раздел «Мои взносы».',
          '2. Укажите сумму и дату платежа, приложите фото чека.',
          '3. Отправьте. Взнос попадёт на подтверждение администратору.',
          '',
          'На баланс взнос влияет только после подтверждения. Пока он на рассмотрении,',
          'долг не уменьшается — это не задержка, а правило учёта.',
          '',
          'Что ещё стоит знать:',
          '- Отпуск и больничный отмечайте в разделе «Отсутствия»: за эти дни вода на вас',
          '  не раскладывается.',
          '- «Ты должен N ₽» на главной — ваша доля в уже оплаченных заказах за вычетом взносов.',
          '- Любое число можно раскрыть: в разделе «Фонд» видно, из чего сложился ваш баланс.',
        ].join('\n'),
      },
    });
    console.info('Заведена закреплённая инструкция «Как пользоваться кассой»');
  }

  console.info(`Администратор: ${admin.email} (${admin.id})`);
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (error: unknown) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });
